#!/usr/bin/env python3
"""Regenerate .kiro/steering/codebase-map.md: a compact, always-current map so agents stop rediscovering the repo.

Frontier teams invest in agent context; this keeps the map deterministic (no model call) and cheap to refresh.
"""
import ast
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / ".kiro" / "steering" / "codebase-map.md"
SKIP = ("site/", "docs/", "_site/", "evidence/", ".github/", "powers/", "tests/fakes/")


def python_symbols(path: pathlib.Path) -> list[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return []
    out = []
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and not n.name.startswith("_"):
            doc = (ast.get_docstring(n) or "").strip().splitlines()
            out.append(f"`{n.name}`" + (f": {doc[0][:90]}" if doc else ""))
    return out


def build() -> str:
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, stdin=subprocess.DEVNULL).stdout.split()
    lines = ["---", "inclusion: auto", "name: codebase-map",
             "description: Map of this repository's code, entry points and public functions. Use when looking for where something lives or before adding a new module.",
             "---", "# Codebase map (generated by tools/frontier/context_map.py; do not edit by hand)", ""]
    for f in sorted(files):
        if f.startswith(SKIP) or not f.endswith((".py", ".sh", ".pl", ".cgi", ".ts")):
            continue
        p = ROOT / f
        syms = python_symbols(p) if f.endswith(".py") else []
        first = ""
        if f.endswith(".py"):
            try:
                first = (ast.get_docstring(ast.parse(p.read_text(encoding="utf-8"))) or "").strip().splitlines()[0][:100]
            except (SyntaxError, IndexError, UnicodeDecodeError):
                first = ""
        lines.append(f"- `{f}`" + (f": {first}" if first else ""))
        lines += [f"  - {s}" for s in syms[:12]]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("codebase-map.md is stale; run tools/frontier/context_map.py", file=sys.stderr)
            return 1
        print("codebase-map.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
